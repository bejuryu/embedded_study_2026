/* startup.S - ESP32-P4 베어메탈 RISC-V 스타트업 코드 */
/* main() 진입 전 C 런타임 환경(스택, BSS 초기화)을 구성한다. */

.section .text.init
.global _start
.type _start, @function

_start:
    /* ==================================================================== */
    /* 1. 스택 포인터(Stack Pointer) 초기화                                 */
    /* ==================================================================== */
    
    // la (Load Address): 링커 심볼의 메모리 주소를 레지스터에 적재하는 의사 명령어.
    // __stack_top은 링커 스크립트(esp32p4.ld)에서 SRAM 최상단으로 정의된 심볼이며,
    // 이를 sp 레지스터에 설정하여 함수 호출 시 사용할 스택 영역의 기준점을 확보한다.
    la sp, __stack_top

    /* ==================================================================== */
    /* 2. BSS 영역 제로 초기화                                              */
    /* ==================================================================== */
    // 링커 스크립트에서 정의된 BSS 영역의 시작/끝 주소를 t0, t1에 적재한다.
    la t0, __bss_start
    la t1, __bss_end
    
    // bgeu (Branch if Greater or Equal, Unsigned): t0 >= t1이면 BSS 영역이 비어 있으므로
    // 초기화 루프를 건너뛰고 bss_cleared로 분기한다.
    bgeu t0, t1, bss_cleared

clear_bss_loop:
    // sw (Store Word): zero 레지스터(x0, 상시 0)의 값을 t0가 가리키는 주소에 4바이트 기록한다.
    sw zero, 0(t0)
    
    // addi (Add Immediate): 다음 워드 주소로 이동하기 위해 t0에 4를 가산한다.
    addi t0, t0, 4
    
    // bltu (Branch if Less Than, Unsigned): t0 < t1이면 미초기화 영역이 잔존하므로
    // clear_bss_loop로 분기하여 초기화를 계속한다.
    bltu t0, t1, clear_bss_loop

bss_cleared:
    /* ==================================================================== */
    /* 3. C 언어 main() 함수 진입                                           */
    /* ==================================================================== */
    
    // call: main 심볼로 점프하며, 복귀 주소를 ra 레지스터에 저장한다.
    call main

    /* ==================================================================== */
    /* 4. main() 복귀 시 안전 무한루프                                      */
    /* ==================================================================== */
end_loop:
    // main()이 반환된 경우, 임의 메모리 실행에 의한 시스템 오동작을 방지하기 위해
    // 무한루프로 CPU를 정지 상태로 유지한다.
    j end_loop
